/**
 * 批准后注入执行轮的一次性上下文。
 *
 * 计划正文已经保存在会话工具调用与 `meta.plan` 里，但执行轮仍显式带上完整计划：
 * 模型在长上下文 / 压缩后仍有一份权威文本可依，不会凭记忆"大概按计划做"。
 */
/** 执行轮 extraContext 的首行（冒烟 / 截图的桩服务按它寻址，勿改文案后忘记同步） */
export const PLAN_EXECUTION_CONTEXT_TITLE = '【已批准的实施计划，现在开始执行】'

export function buildPlanExecutionContext(markdown: string): string {
  return [
    PLAN_EXECUTION_CONTEXT_TITLE,
    markdown.trim(),
    '',
    '执行要求：',
    '1. 严格按计划推进；先用 todo_write 建立任务清单，每完成一步更新清单。',
    '2. 改动集中在本计划范围内，不擅自扩大；计划与现状冲突时先停下来说明，不要硬套。',
    '3. 完成后用简短总结说明结果与验证情况。',
  ].join('\n')
}
